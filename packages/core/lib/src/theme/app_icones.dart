/// Tamanhos de ícone do painel, em pixels lógicos.
abstract final class AppIcones {
  /// 20: ícone dentro de botão ou campo.
  static const pequeno = 20.0;

  /// 24: ícone padrão (navegação, listas).
  static const padrao = 24.0;

  /// 48: ilustração de estado vazio ou de falha.
  static const destaque = 48.0;
}
